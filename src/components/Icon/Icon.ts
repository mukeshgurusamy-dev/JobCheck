export function createIcon(options: IconOptions): SVGSVGElement {
  const {
    name,
    size = "md",
    colorClass,
    className,
    ariaHidden = true,
    label
  } = options;

  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");

  const classList = ["c-icon", `c-icon--${size}`];
  if (name === "loader") {
    classList.push("c-icon--spin");
  }
  if (colorClass) {
    classList.push(colorClass);
  }
  if (className) {
    classList.push(className);
  }

  svg.setAttribute("class", classList.join(" "));

  if (ariaHidden) {
    svg.setAttribute("aria-hidden", "true");
  } else if (label) {
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", label);
  }

  const inner = ICON_SVGS[name];
  if (inner) {
    svg.innerHTML = inner;
  }

  return svg;
}
